// Heuristic: a row is a plausible full name if it has 2-3 word tokens,
// none of which look like an email, number, placeholder or noise token.
const NOISE_TOKENS = new Set([
  'admin',
  'guest',
  'root',
  'login',
  'demo_user',
  'contact-form',
  'null',
  'undefined',
  'unknown',
  'test',
  'info',
  'xxx',
  'n/a',
  'na',
  '—',
  '---',
  '???',
  '0',
  '123',
  '12345',
  '42',
]);

const isEmail = (s: string) => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(s);
const isNumeric = (s: string) => /^[0-9]+$/.test(s.trim());

export function isLikelyFullName(value: string): boolean {
  const v = value.trim();
  if (!v) return false;
  if (isEmail(v)) return false;
  if (isNumeric(v)) return false;
  if (NOISE_TOKENS.has(v.toLowerCase())) return false;
  const tokens = v.split(/\s+/);
  if (tokens.length < 2 || tokens.length > 3) return false;
  // every token should be alphabetic (Cyrillic/Latin), at least 2 chars
  return tokens.every((t) => /^[\p{L}]{2,}$/u.test(t));
}

export function makeId(): string {
  return Math.random().toString(36).slice(2, 10) + Date.now().toString(36).slice(-4);
}
